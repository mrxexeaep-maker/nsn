import jison from 'jison'

import { MERMAID_RELEASE, sourceURL, type Grammar } from './grammars'

/**
 * A JISON grammar as an ES module exporting its parser, built with the options Mermaid's build
 * uses (`.build/jisonTransformer.ts`), under a header naming where it came from.
 */
export function parserModule(grammar: Grammar, source: string): string {
  const generator = new jison.Generator(source, { moduleType: 'js', 'token-stack': true })
  const parser = generator.generate({ moduleMain: '() => {}' })
  return [
    '// @ts-nocheck',
    `// Generated by \`bun run generate:mermaid-grammars\` from ${grammar.source}`,
    `// in ${MERMAID_RELEASE.tag} (${sourceURL(grammar.source)}).`,
    '// Copyright (c) 2014 - 2022 Knut Sveidqvist. MIT License; see MERMAID-LICENSE.txt.',
    '// Do not edit: change the pinned release in tools/generate/mermaid-grammars and regenerate.',
    parser,
    'parser.parser = parser',
    'export default parser',
    ''
  ].join('\n')
}
